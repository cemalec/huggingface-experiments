#!/usr/bin/env python3
"""Emit per-chunk workflow files from run_manifest.jsonl.

Reads the manifest (one row per seed x tier from sample_instructions.py),
partitions into chunks of <= --max-subagents (default 1000, the Claude Code
subagent lifetime cap), keeping both tiers of the same seed in the same
chunk, and writes one self-contained workflow file per chunk by replacing
generate_triples_workflow.js's EDIT-PER-RUN block with a chunk-specific
RUN const and JOBS array.

Each emitted file is runnable as a standalone Claude Code Workflow:
    Workflow({ scriptPath: "projects/paraphraser/data/runs/chunk_NNN.workflow.js" })

After all chunks complete, append a row per chunk to triples.runs.md.

The emitter never invents random numbers or timestamps inside the workflow
file's source (the sandbox statically rejects `Date.now`/`Math.random`/`new Date`);
both are computed here in Python and inlined as string literals.
"""
from __future__ import annotations

import argparse
import json
import re
import time
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent
DEFAULT_MANIFEST = PROJECT_DIR / "data" / "run_manifest.jsonl"
DEFAULT_TEMPLATE = PROJECT_DIR / "generate_triples_workflow.js"
DEFAULT_OUT_DIR = PROJECT_DIR / "data" / "runs"

EDIT_BLOCK_RE = re.compile(
    r"// =+ EDIT PER RUN =+.*?// =+ END EDIT PER RUN =+",
    re.DOTALL,
)


def group_by_seed(rows: list[dict]) -> list[list[dict]]:
    """Group consecutive rows by seed_idx so both tiers of one seed stay together."""
    groups: list[list[dict]] = []
    current_idx = None
    current: list[dict] = []
    for r in rows:
        if r["seed_idx"] != current_idx:
            if current:
                groups.append(current)
            current_idx = r["seed_idx"]
            current = [r]
        else:
            current.append(r)
    if current:
        groups.append(current)
    return groups


def partition(groups: list[list[dict]], max_subagents: int) -> list[list[dict]]:
    """Pack seed-groups into chunks without exceeding max_subagents per chunk."""
    chunks: list[list[dict]] = []
    cur: list[dict] = []
    for g in groups:
        if len(g) > max_subagents:
            raise SystemExit(f"single seed has {len(g)} jobs > --max-subagents {max_subagents}")
        if len(cur) + len(g) > max_subagents and cur:
            chunks.append(cur)
            cur = []
        cur.extend(g)
    if cur:
        chunks.append(cur)
    return chunks


def build_edit_block(run_id: str, gen_timestamp: str, jobs: list[dict]) -> str:
    lines = [
        "// ============================ EDIT PER RUN ==================================",
        "// Generated by emit_chunks.py — do not hand-edit.",
        "const RUN = {",
        f"  run_id: {json.dumps(run_id)},",
        f"  gen_timestamp: {json.dumps(gen_timestamp)},",
        "  gen_backend: 'claude-code-workflow',",
        "  prompt_version: 'v1',",
        "}",
        "",
        "const JOBS = [",
    ]
    for j in jobs:
        # Trim manifest row to fields the workflow consumes.
        slim = {
            "seed_idx":     j["seed_idx"],
            "source":       j["source"],
            "domain":       j["domain"],
            "source_id":    j["source_id"],
            "tier":         j["tier"],
            "model":        j["model"],
            "model_id":     j["model_id"],
            "instructions": j["instructions"],
        }
        lines.append("  " + json.dumps(slim, ensure_ascii=False) + ",")
    lines.append("]")
    lines.append("// ========================== END EDIT PER RUN ================================")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", default=str(DEFAULT_MANIFEST))
    ap.add_argument("--template", default=str(DEFAULT_TEMPLATE))
    ap.add_argument("--out-dir", default=str(DEFAULT_OUT_DIR))
    ap.add_argument("--max-subagents", type=int, default=1000,
                    help="cap per chunk (default 1000, matches Claude Code limit)")
    ap.add_argument("--label", default="bulk",
                    help="run_id label segment (default: 'bulk' -> claude-bulk-001-...)")
    args = ap.parse_args()

    manifest_path = Path(args.manifest)
    template_path = Path(args.template)
    out_dir = Path(args.out_dir)

    rows = [json.loads(l) for l in manifest_path.read_text().splitlines() if l]
    chunks = partition(group_by_seed(rows), args.max_subagents)

    template = template_path.read_text()
    if not EDIT_BLOCK_RE.search(template):
        raise SystemExit(f"template missing EDIT-PER-RUN sentinels: {template_path}")

    # One run_id stamp per emit invocation (chunks differ by index).
    ts_compact = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
    ts_iso = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

    out_dir.mkdir(parents=True, exist_ok=True)
    print(f"emitting {len(chunks)} chunks to {out_dir}/")
    for i, chunk in enumerate(chunks, 1):
        run_id = f"claude-{args.label}-{i:03d}-{ts_compact}"
        edit_block = build_edit_block(run_id, ts_iso, chunk)
        emitted = EDIT_BLOCK_RE.sub(lambda _m: edit_block, template)
        out_path = out_dir / f"chunk_{i:03d}.workflow.js"
        out_path.write_text(emitted)
        n_seeds = len({j["seed_idx"] for j in chunk})
        print(f"  {out_path.name}  {len(chunk):4d} subagents  {n_seeds:4d} seeds  run_id={run_id}")


if __name__ == "__main__":
    main()
