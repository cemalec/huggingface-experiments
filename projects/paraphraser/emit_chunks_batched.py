#!/usr/bin/env python3
"""Emit BATCHED per-chunk workflow files from run_manifest.jsonl.

Difference from emit_chunks.py: each subagent ("batch") handles --batch-sources
sources of the SAME tier instead of one, amortizing the ~11k-token fixed
per-subagent overhead. Measured ~775 tok/triple at 4 sources, ~lower at 8.

Steps:
  1. Read the manifest (one row per seed x tier).
  2. Drop (source_id, tier) pairs already present in --done-file so re-runs don't
     regenerate completed work (e.g. chunk_001's seeds).
  3. Group remaining jobs by tier and pack --batch-sources sources per batch,
     labelling them S1..SN; each batch becomes one subagent.
  4. Pack batches into chunk files under --max-bytes (the Workflow tool rejects
     scripts over 524288 bytes), substituting the template's EDIT-PER-RUN block.

Run each:  Workflow({ scriptPath: "<abs>/data/runs/batched/chunk_NNN.workflow.js" })

Timestamps/run_ids are computed here and inlined as string literals (the sandbox
statically rejects Date.now/Math.random/new Date).
"""
from __future__ import annotations

import argparse
import json
import re
import time
from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent
DEFAULT_MANIFEST = PROJECT_DIR / "data" / "run_manifest.jsonl"
DEFAULT_TEMPLATE = PROJECT_DIR / "generate_triples_batched_workflow.js"
DEFAULT_OUT_DIR = PROJECT_DIR / "data" / "runs" / "batched"
DEFAULT_DONE = PROJECT_DIR / "data" / "triples.claude-code.jsonl"

EDIT_BLOCK_RE = re.compile(
    r"// =+ EDIT PER RUN =+.*?// =+ END EDIT PER RUN =+",
    re.DOTALL,
)


def load_done(done_path: Path) -> set[tuple[str, str]]:
    """Return the set of (source_text, tier) already generated, to skip on re-run.

    Keyed on the source TEXT, not source_id: source_id is per-document, so several
    distinct seed sentences share one id (e.g. two sentences from the same Wikipedia
    article). build_seeds.py dedupes source text, so (source, tier) is the exact key.
    """
    done: set[tuple[str, str]] = set()
    if not done_path.exists():
        return done
    for line in done_path.read_text().splitlines():
        if not line:
            continue
        r = json.loads(line)
        src, tier = r.get("source"), r.get("tier")
        if src and tier:
            done.add((src, tier))
    return done


def make_batches(rows: list[dict], batch_sources: int) -> list[dict]:
    """Group same-tier jobs into batches of <= batch_sources, labelled S1..SN."""
    by_tier: dict[str, list[dict]] = {}
    for r in rows:
        by_tier.setdefault(r["tier"], []).append(r)

    batches: list[dict] = []
    for tier, jobs in by_tier.items():
        for i in range(0, len(jobs), batch_sources):
            group = jobs[i:i + batch_sources]
            sources = [{
                "ref": f"S{k}",
                "source": j["source"],
                "domain": j["domain"],
                "source_id": j["source_id"],
                "instructions": j["instructions"],
            } for k, j in enumerate(group, 1)]
            batches.append({
                "tier": tier,
                "model": group[0]["model"],
                "model_id": group[0]["model_id"],
                "sources": sources,
            })
    return batches


def pack_chunks(batches: list[dict], max_bytes: int) -> list[list[dict]]:
    """Pack batches into chunks whose serialized BATCHES array stays under max_bytes."""
    # Reserve room for the template scaffolding around the BATCHES array.
    budget = max_bytes - 8192
    chunks: list[list[dict]] = []
    cur: list[dict] = []
    cur_bytes = len("const BATCHES = [\n]")
    for b in batches:
        line = "  " + json.dumps(b, ensure_ascii=False) + ",\n"
        nbytes = len(line.encode("utf-8"))
        if nbytes > budget:
            raise SystemExit(f"single batch is {nbytes} B > budget {budget}; lower --batch-sources")
        if cur and cur_bytes + nbytes > budget:
            chunks.append(cur)
            cur, cur_bytes = [], len("const BATCHES = [\n]")
        cur.append(b)
        cur_bytes += nbytes
    if cur:
        chunks.append(cur)
    return chunks


def build_edit_block(run_id: str, gen_timestamp: str, batches: list[dict]) -> str:
    lines = [
        "// ============================ EDIT PER RUN ==================================",
        "// Generated by emit_chunks_batched.py — do not hand-edit.",
        "const RUN = {",
        f"  run_id: {json.dumps(run_id)},",
        f"  gen_timestamp: {json.dumps(gen_timestamp)},",
        "  gen_backend: 'claude-code-workflow',",
        "  prompt_version: 'v1-batch',",
        "}",
        "",
        "const BATCHES = [",
    ]
    for b in batches:
        lines.append("  " + json.dumps(b, ensure_ascii=False) + ",")
    lines.append("]")
    lines.append("// ========================== END EDIT PER RUN ================================")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", default=str(DEFAULT_MANIFEST))
    ap.add_argument("--template", default=str(DEFAULT_TEMPLATE))
    ap.add_argument("--out-dir", default=str(DEFAULT_OUT_DIR))
    ap.add_argument("--done-file", default=str(DEFAULT_DONE),
                    help="skip (source_id,tier) pairs already present here (default: the live triples file)")
    ap.add_argument("--batch-sources", type=int, default=8,
                    help="sources per subagent (default 8)")
    ap.add_argument("--max-bytes", type=int, default=500000,
                    help="max emitted file size; Workflow rejects >524288 (default 500000)")
    ap.add_argument("--label", default="batch8")
    args = ap.parse_args()

    rows = [json.loads(l) for l in Path(args.manifest).read_text().splitlines() if l]
    done = load_done(Path(args.done_file))
    remaining = [r for r in rows if (r["source"], r["tier"]) not in done]
    print(f"manifest {len(rows)} jobs; {len(done)} (source,tier) already done; {len(remaining)} remaining")

    batches = make_batches(remaining, args.batch_sources)
    chunks = pack_chunks(batches, args.max_bytes)

    template = Path(args.template).read_text()
    if not EDIT_BLOCK_RE.search(template):
        raise SystemExit(f"template missing EDIT-PER-RUN sentinels: {args.template}")

    ts_compact = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
    ts_iso = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    total_triples = 0
    print(f"emitting {len(chunks)} batched chunks to {out_dir}/")
    for i, chunk in enumerate(chunks, 1):
        run_id = f"claude-{args.label}-{i:03d}-{ts_compact}"
        edit_block = build_edit_block(run_id, ts_iso, chunk)
        emitted = EDIT_BLOCK_RE.sub(lambda _m: edit_block, template)
        out_path = out_dir / f"chunk_{i:03d}.workflow.js"
        out_path.write_text(emitted)
        n_sources = sum(len(b["sources"]) for b in chunk)
        n_triples = sum(len(s["instructions"]) for b in chunk for s in b["sources"])
        total_triples += n_triples
        print(f"  {out_path.name}  {len(chunk):3d} subagents  {n_sources:4d} sources  "
              f"{n_triples:5d} triples  {out_path.stat().st_size:6d} B  run_id={run_id}")
    print(f"total: {total_triples} triples across {len(chunks)} chunks")


if __name__ == "__main__":
    main()
